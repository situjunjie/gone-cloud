package cn.iocoder.yudao.module.project.enums;

import cn.iocoder.yudao.framework.common.core.ArrayValuable;
import lombok.AllArgsConstructor;
import lombok.Getter;

import java.util.Arrays;

@Getter
@AllArgsConstructor
public enum ProjectVisibilityEnum implements ArrayValuable<String> {

    PUBLIC("PUBLIC", "公开"),
    PRIVATE("PRIVATE", "私密");

    public static final String[] ARRAYS = Arrays.stream(values()).map(ProjectVisibilityEnum::getValue)
            .toArray(String[]::new);

    private final String value;
    private final String name;

    @Override
    public String[] array() {
        return ARRAYS;
    }

}
